#!/usr/bin/env bash
# Explicit owner update: Bank B OFF, EVE stopped; preserve source/state and use fast-forward only.
set -euo pipefail
cd "$(dirname "$0")/.."
PY="$(pwd)/.venv/bin/python"; [ -x "$PY" ] || PY=python3
[ -d .git ] || { echo "Git install required. ZIP installs must be backed up and replaced manually."; exit 1; }
HEADER=firmware/eve_controller/eve_config.h
LOCAL_CONFIG=config/local.json

check_checkout() {
  [ "$(git branch --show-current)" = main ] || { echo "Stop. Switch to a clean main branch first."; exit 1; }
  [ -z "$(git status --porcelain -- . ":(exclude)$HEADER")" ] && git diff --cached --quiet -- "$HEADER" ||
    { echo "Stop. Preserve local changes and unstage the generated firmware header before updating."; exit 1; }
  "$PY" - <<'PY'
from pathlib import Path
from eve3 import config, firmware
import subprocess
path = Path('firmware/eve_controller/eve_config.h')
if subprocess.run(['git', 'diff', '--quiet', 'HEAD', '--', str(path)]).returncode:
    if path.read_text() != firmware.header_text(config.load()):
        raise SystemExit('Stop. The modified firmware header differs from the header generated by your current settings.')
PY
  "$PY" - <<'PY'
import sys
sys.path.insert(0, 'tools')
from _common import eve_running
if eve_running():
    raise SystemExit('Stop EVE or its service before updating. Bank B actuator power must be off.')
PY
}

check_checkout
read -r -p "Bank B is OFF and EVE/service stopped? Type YES: " answer
[ "$answer" = YES ] || exit 1
before=$(git rev-parse HEAD)
git fetch origin main
target=$(git rev-parse --verify FETCH_HEAD)
if [ "$before" = "$target" ]; then
  echo "EVE is already at the latest revision."
  exit 0
fi
if ! git merge-base --is-ancestor "$before" "$target"; then
  echo "Stop. The fetched main branch cannot be fast-forwarded from this checkout."
  exit 1
fi

# Check the exact candidate with clean defaults, then validate the owner's local settings.
verify_dir=$(mktemp -d)
trap 'rm -rf "$verify_dir"' EXIT
git archive "$target" | tar -x -C "$verify_dir"
echo "Checking the fetched revision before applying it."
(
  cd "$verify_dir"
  "$PY" -m unittest discover -s tests -t .
  "$PY" tools/check_repo.py
  "$PY" tools/check_clone.py
)
if [ -f "$LOCAL_CONFIG" ]; then
  cp "$LOCAL_CONFIG" "$verify_dir/$LOCAL_CONFIG"
fi
(cd "$verify_dir" && "$PY" tools/gen_header.py)

check_checkout
if [ "$(git rev-parse HEAD)" != "$before" ]; then
  echo "Stop. HEAD changed during verification. Review the checkout before retrying."
  exit 1
fi
if [ -f "$LOCAL_CONFIG" ] || [ -f "$verify_dir/$LOCAL_CONFIG" ]; then
  cmp -s "$LOCAL_CONFIG" "$verify_dir/$LOCAL_CONFIG" ||
    { echo "Stop. Local settings changed during verification. Review them before retrying."; exit 1; }
fi
if ! cmp -s "$HEADER" "$verify_dir/$HEADER" ||
   ! git diff --quiet "$before" "$target" -- firmware/eve_controller; then
  firmware_changed=1
else
  firmware_changed=0
fi

backup_dir="${EVE_BACKUP_DIR:-$HOME/eve_backups}"
mkdir -p "$backup_dir"
chmod 700 "$backup_dir"
umask 077
backup=$(mktemp --tmpdir="$backup_dir" --suffix=.tar.gz "eve-before-update-$(date +%Y%m%d-%H%M%S)-XXXXXX")
if ! tar --exclude='./.git' --exclude='./.venv' --exclude='./third_party' --exclude='./models' --exclude='*/__pycache__' -czf "$backup" .; then
  rm -f "$backup"
  echo "Stop. The private backup did not complete."
  exit 1
fi
echo "Backup: $backup"
git restore --source="$before" --worktree -- "$HEADER"
if ! git merge --ff-only --no-autostash --no-overwrite-ignore "$target"; then
  tar -xzf "$backup" "./$HEADER"
  echo "Update stopped. The original header and backup were retained."
  exit 1
fi
cp "$verify_dir/$HEADER" "$HEADER"
"$PY" - "$backup_dir" <<'PY'
import sys
from pathlib import Path
backups = sorted(Path(sys.argv[1]).glob('eve-before-update-*.tar.gz'), key=lambda p: p.stat().st_mtime, reverse=True)
for old in backups[2:]:
    old.unlink()
PY
echo "Updated and checked. Read CHANGELOG.md for any dependency changes before restarting EVE."
if [ "$firmware_changed" = 1 ]; then
  echo "Firmware changed. Follow M02 to flash and verify the live fingerprint before restoring actuator power."
fi
