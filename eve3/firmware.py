"""M02 - generates firmware/eve_controller/eve_config.h from the config and fingerprints it.

The Mega reports the fingerprint in its SYNC reply. The Pi computes the same fingerprint from its own
config, so a stale flash (old calibration, old limits) is detected and motion is refused.
"""
from __future__ import annotations
import hashlib


def _b(v) -> str:
    return "true" if v else "false"


def header_body(cfg: dict) -> str:
    d, h, s, fw = cfg["drive"], cfg["head"], cfg["safety"], cfg["firmware"]
    cal, pins = cfg["sensors"]["cliff_calibration"], cfg["pins"]["mega"]
    left, right = pins["left"], pins["right"]
    names = ("STBY", "A1", "A2", "PWMA", "B1", "B2", "PWMB")
    lines = [
        f"static const bool DRIVE_ENABLED = {_b(fw['drive_enabled'])};",
        f"static const bool HEAD_ENABLED = {_b(fw['head_enabled'])};",
        f"static const bool WATCHDOG_ENABLED = {_b(fw['watchdog_enabled'])};",
        f"static const bool REVERSE_ALLOWED = {_b(d['reverse_allowed'])};",
        f"static const bool PIVOT_ALLOWED = {_b(d['pivot_allowed'])};",
        f"static const bool CLIFF_CALIBRATED = {_b(cal['calibrated'])};",
        "static const uint8_t CLIFF_EDGE_LEVEL[3] = {%s};" % ",".join(str(int(v)) for v in cal["edge_level"]),
        f"static const int DRIVE_MAX = {int(d['max_pwm'])};",
        f"static const int RAMP_PER_SECOND = {int(d['ramp_per_second'])};",
        f"static const unsigned long REVERSE_MS = {int(d['reverse_deadtime_ms'])};",
        f"static const long PAN_MIN = {int(h['pan_min_steps'])}, PAN_MAX = {int(h['pan_max_steps'])};",
        f"static const long TILT_MIN = {int(h['tilt_min_steps'])}, TILT_MAX = {int(h['tilt_max_steps'])};",
        f"static const unsigned long HB_TIMEOUT_MS = {int(s['mega_watchdog_ms'])};",
        f"static const unsigned long DRIVE_LEASE_MS = {int(d['command_lease_ms']) + 50};",
        "static const unsigned long HEAD_LEASE_MS = 350;",
    ]
    lines += [f"static const uint8_t L_{n} = {int(p)};" for n, p in zip(names, left)]
    lines += [f"static const uint8_t R_{n} = {int(p)};" for n, p in zip(names, right)]
    lines += [
        "static const uint8_t PAN[4] = {%s};" % ",".join(str(int(p)) for p in pins["pan"]),
        "static const uint8_t TILT[4] = {%s};" % ",".join(str(int(p)) for p in pins["tilt"]),
        f"static const uint8_t PIR_PIN = {int(pins['pir'])};",
        "static const uint8_t CLIFF[3] = {%s};" % ",".join(str(int(p)) for p in pins["cliff"]),
    ]
    return "\n".join(lines) + "\n"


def firmware_id(cfg: dict) -> str:
    return hashlib.sha256(header_body(cfg).encode("ascii")).hexdigest()[:12]


def header_text(cfg: dict) -> str:
    return ("// Generated by tools/gen_header.py from config. Do not edit by hand.\n"
            "#ifndef EVE_CONFIG_H\n#define EVE_CONFIG_H\n#include <stdint.h>\n"
            f'static const char FIRMWARE_ID[] = "{firmware_id(cfg)}";\n'
            + header_body(cfg) + "#endif\n")
