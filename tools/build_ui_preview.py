#!/usr/bin/env python3
"""Build the guide's static previews from the robot's public web assets."""
import argparse
from ast import literal_eval
from base64 import b64encode
from html import escape
import json
from pathlib import Path
import re
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "eve3/web"
OUTPUT = ROOT / "docs/assets/ui-preview"
CUE_SAMPLES = ("happy", "love", "surprised")
PREVIEW_CSP = "default-src 'none'; style-src 'unsafe-inline'"


def between(source, start, stop):
    _, remainder = source.split(start, 1)
    value, _ = remainder.split(stop, 1)
    return value


def page(title, style, body):
    return (f'<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            f'<meta http-equiv="Content-Security-Policy" content="{PREVIEW_CSP}">\n'
            f'<title>{escape(title)}</title>\n<style>{style}</style>\n</head>\n<body>{body}</body></html>\n')


def kiosk_preview():
    source = (WEB / "face.html").read_text(encoding="utf-8")
    style = between(source, "<style>", "</style>")
    screen = between(source, "<body>", '<details id="sound-settings"').strip()
    if 'id="face"' not in screen or 'id="extended"' not in screen or "<script" in screen:
        raise ValueError("Expected only the EVE kiosk display markup in the preview")
    core = literal_eval(between(source, "const core = new Set(", ");"))
    catalog = json.loads((WEB / "expressions.json").read_text(encoding="utf-8"))
    with ZipFile(WEB / "expression-sounds.zip") as sounds:
        samples = {name: "data:audio/wav;base64," + b64encode(sounds.read(f"{name}.wav")).decode("ascii")
                   for name in CUE_SAMPLES}
    style += ("html,body{cursor:default} #face.blink .eye{height:2vh} @media(prefers-reduced-motion:reduce)"
              "{*,*::before,*::after{animation:none!important;transition:none!important}}")
    data = {"screen": page("EVE touchscreen", style, screen), "expressions": catalog["expressions"],
            "core": core, "samples": samples}
    art = (WEB / "eva-face-art.js").read_text(encoding="utf-8")
    return ("/* Generated by tools/build_ui_preview.py from the robot's web assets. */\n"
            + art.rstrip() + "\nwindow.EveKioskPreview = " + json.dumps(data, ensure_ascii=False) + ";\n")


def control_preview():
    source = (WEB / "control.html").read_text(encoding="utf-8")
    style = between(source, "<style>", "</style>")
    markup = between(source, "<main>", "</main>")
    markup = re.sub(r"<a\b[^>]*>(.*?)</a>", r"<span>\1</span>", markup, flags=re.S)
    status = [
        ("Mega", "Online · example firmware matches"),
        ("Distance mm (FL, FR, rear)", "[null, null, null]"),
        ("Tilt deg", "Unavailable"),
        ("Cliff raw (FL, rear, FR)", "[1, 1, 1] · not calibrated"),
        ("Person sensor (PIR)", "false"),
        ("Session", "Not active"),
        ("Pi supply flags", "Sample only"),
        ("Wheels allowed", "No · awaiting commissioning"),
        ("Head allowed", "No · awaiting commissioning"),
        ("Head", "Not homed"),
        ("Face", "Idle"),
        ("Features", "The Pi shows its enabled features here"),
        ("Still to commission", "Power, motor current, test area, wheels and head"),
    ]
    rows = "\n".join(f"<tr><td>{escape(name)}</td><td>{escape(value)}</td></tr>" for name, value in status)
    markup = markup.replace('<div id="msg"></div>', '<p id="msg">Sample status before calibration</p>')
    markup = markup.replace('<table id="st"></table>', f'<table id="st">\n{rows}\n</table>')
    markup = markup.replace('<div class="row" id="expr"></div>',
                            '<div class="row" id="expr"><select aria-label="Face expression">'
                            '<option>Happy</option></select><button>Show expression</button></div>')
    if "<script" in markup or "<form" in markup or "<a " in markup:
        raise ValueError("The control preview must contain static, read-only markup")
    style += ("fieldset{border:0;margin:0;padding:0;min-width:0}"
              "fieldset :disabled{opacity:.8;cursor:default}"
              "@media(max-width:480px){td:first-child{white-space:normal}}")
    return page("EVE control screen preview", style, f'<main><fieldset disabled>\n{markup}</fieldset></main>')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in (("kiosk-data.js", kiosk_preview()), ("control.html", control_preview())):
        path = OUTPUT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != data:
                parser.exit(1, f"{name} is stale; run python3 tools/build_ui_preview.py\n")
        else:
            OUTPUT.mkdir(parents=True, exist_ok=True)
            path.write_text(data, encoding="utf-8")


if __name__ == "__main__":
    main()
